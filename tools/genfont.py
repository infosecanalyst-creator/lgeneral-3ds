#!/usr/bin/env python3
"""Render DejaVu Sans glyphs (Latin-1) into anti-aliased alpha bitmaps for dsui (C source).
DejaVu fonts: Bitstream Vera / DejaVu license (free to embed and redistribute)."""
import sys
from PIL import Image, ImageDraw, ImageFont

FONTS = [  # (c name, ttf, pixel size)
    ("dsfont_small", "/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed.ttf", 10),
    ("dsfont_body",  "/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed.ttf", 12),
    ("dsfont_bold",  "/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed-Bold.ttf", 12),
    ("dsfont_title", "/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed-Bold.ttf", 15),
]
out = ["/* generated by tools/genfont.py from DejaVu Sans Condensed (DejaVu/Bitstream Vera license) */",
       '#include "dsui_font.h"', ""]
for cname, path, size in FONTS:
    f = ImageFont.truetype(path, size)
    asc, desc = f.getmetrics()
    data = []; glyphs = []
    for cp in range(32, 256):
        ch = chr(cp)
        if cp >= 127 and cp < 160:
            glyphs.append((0, 0, 0, 0, 0, 0)); continue
        bbox = f.getbbox(ch)  # left, top, right, bottom relative to origin (top = ascent line)
        adv = round(f.getlength(ch))
        w = max(0, bbox[2] - bbox[0]); h = max(0, bbox[3] - bbox[1])
        off = len(data)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-bbox[0], -bbox[1]), ch, font=f, fill=255)
            data.extend(im.tobytes())
        glyphs.append((off, w, h, bbox[0], bbox[1], adv))
    out.append(f"static const unsigned char {cname}_data[{max(1,len(data))}] = {{")
    for i in range(0, len(data), 24):
        out.append("  " + ",".join(str(b) for b in data[i:i+24]) + ",")
    if not data: out.append("0")
    out.append("};")
    out.append(f"static const DSGlyph {cname}_glyphs[224] = {{")
    for g in glyphs:
        out.append("  {%d,%d,%d,%d,%d,%d}," % g)
    out.append("};")
    out.append(f"const DSFont {cname} = {{ {asc + desc}, {asc}, {cname}_glyphs, {cname}_data }};")
    out.append("")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
print("ok", sys.argv[1])
